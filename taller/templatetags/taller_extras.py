@register.simple_tag
def icono(nombre, clase=""):
    """Renderiza un icono SVG en línea: {% icono "users" %}."""
    trazos = _ICONOS.get(nombre, "")
    return format_html(
        '<svg class="icon {}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" '
        'aria-hidden="true" focusable="false">{}</svg>',
        clase,
        mark_safe(trazos),
    )


@register.filter
def moneda(valor):
    return formato.formatear_moneda(valor)


@register.filter
def clase_estado(valor):
    return formato.CLASES_ESTADO.get(valor, "muted")


@register.filter
def es_ancho(campo):
    """Los campos de texto largo ocupan las dos columnas del formulario."""
    return isinstance(campo.field.widget, forms.Textarea)


@register.filter
def es_check(campo):
    return isinstance(campo.field.widget, forms.CheckboxInput)
